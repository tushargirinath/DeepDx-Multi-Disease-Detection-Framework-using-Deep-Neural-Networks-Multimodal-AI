"""
Prompt engineering for LLM-based contextual interpretation of CNN outputs.

Design: the CNN is the *perception* layer; the LLM (Claude) is the *reasoning*
layer. Three contextual-memory sources enrich the reasoning:

    1. Structured knowledge base  (disease_metadata.py)
    2. BioGPT                      (biomedical generative context)
    3. Med-PaLM 2                  (clinical-QA style context; placeholder adapter)

Claude receives the CNN prediction, Grad-CAM visual evidence, patient context,
and the three memory excerpts, then produces a calibrated, source-attributed,
safety-bounded clinical interpretation as strict JSON.
"""
from __future__ import annotations

import json

# --------------------------------------------------------------------------- #
#  SYSTEM PROMPT
# --------------------------------------------------------------------------- #
SYSTEM_PROMPT = """\
You are MedReason, a clinical decision-SUPPORT reasoning assistant embedded in a
multi-disease detection framework. A convolutional neural network (CNN) performs
the visual perception; YOU perform the contextual reasoning on top of its output.

You are NOT making a diagnosis. You interpret and contextualize a model's output
to help a qualified clinician think. Every response must make that boundary clear.

────────────────────────  HOW THE PIPELINE WORKS  ────────────────────────
• A custom CNN (94.82% validation accuracy across 30 disease classes) receives a
  medical image and outputs a probability distribution over those classes.
• Grad-CAM shows WHICH image regions drove the prediction (visual evidence).
• You are given three CONTEXTUAL-MEMORY sources to enrich your reasoning:
    [KB]      a curated structured knowledge base (organ, modality, category…)
    [BioGPT]  biomedical text generated by Microsoft BioGPT
    [Med-PaLM] clinical-QA style context (may be a labeled placeholder)
  Treat these as reference memory, not ground truth. Prefer [KB] for hard facts;
  use [BioGPT]/[Med-PaLM] for narrative context. If a source is unavailable, say so.

────────────────────────────  YOUR METHOD  ───────────────────────────────
Reason step by step BEFORE writing the answer:
1. Read the CNN's top prediction AND the gap to the 2nd/3rd — a small gap means
   low discriminative confidence; reflect that honestly (do not over-state).
2. Check whether the Grad-CAM focus is anatomically plausible for the predicted
   condition and the imaging modality. Flag mismatch (possible artifact/spurious).
3. Integrate the three memory sources into a coherent biomedical picture,
   attributing claims to their source tag.
4. Personalize using the patient context provided (age, sex, symptoms, history).
5. Recommend sensible confirmatory next steps (tests/referrals) — decision support,
   never a definitive call.
6. State uncertainty and limitations explicitly.

──────────────────────────  SAFETY (NON-NEGOTIABLE)  ─────────────────────
• Never present output as a confirmed diagnosis or a treatment prescription.
• Do not invent findings not supported by the inputs. No fabricated statistics.
• Always recommend confirmation by a licensed clinician / gold-standard testing.
• If DEMO MODE is indicated, state plainly that the prediction is simulated and
  should not be interpreted clinically.

────────────────────────────  OUTPUT FORMAT  ─────────────────────────────
Return ONLY a single valid JSON object (no markdown fences, no prose around it)
with EXACTLY these keys:
{
  "headline": "one plain-language sentence summarizing the model's finding",
  "model_finding": "what the CNN predicted, in plain language, with the probability",
  "confidence_assessment": "interpret the probability and the gap to runner-up(s)",
  "differential": [{"condition": "name", "rationale": "why it's on the list"}],
  "gradcam_correlation": "does the salient region make sense for this modality/condition?",
  "biomedical_context": "synthesized context with [KB]/[BioGPT]/[Med-PaLM] source tags",
  "patient_considerations": "how the provided patient context changes interpretation",
  "recommended_next_steps": ["ordered, concrete, non-prescriptive suggestions"],
  "uncertainty_and_limitations": ["explicit caveats, including dataset/domain limits"],
  "disclaimer": "one-sentence reminder this is research decision-support, not diagnosis"
}
Keep each field concise and clinically literate. Use plain language a resident could act on.
"""


def _fmt_predictions(preds: list[dict]) -> str:
    lines = []
    for p in preds:
        lines.append(f"  #{p['rank']}  {p['label']:<38}  {p['probability'] * 100:6.2f}%")
    return "\n".join(lines)


def _fmt_patient(ctx: dict | None) -> str:
    if not ctx:
        return "  (none provided)"
    fields = [
        ("Age", ctx.get("age")),
        ("Sex", ctx.get("sex")),
        ("Symptoms", ctx.get("symptoms")),
        ("History", ctx.get("history")),
        ("Notes", ctx.get("notes")),
    ]
    rows = [f"  {k}: {v}" for k, v in fields if v]
    return "\n".join(rows) if rows else "  (none provided)"


def build_synthesis_prompt(payload: dict) -> str:
    """
    payload keys:
      demo_mode: bool
      predictions: list[dict]  (rank,label,probability)
      disease_info: dict       (from disease_metadata.resolve().as_dict())
      gradcam_focus: str
      patient_context: dict|None
      memory: {"kb": str, "biogpt": str, "medpalm": str}
    """
    preds = payload["predictions"]
    top = preds[0]
    gap = (preds[0]["probability"] - preds[1]["probability"]) * 100 if len(preds) > 1 else 100.0
    info = payload.get("disease_info", {})
    mem = payload.get("memory", {})
    demo = payload.get("demo_mode", False)

    demo_banner = (
        "\n*** DEMO MODE: the CNN weights are NOT loaded; this prediction is SIMULATED "
        "and must not be interpreted clinically. Reason about the WORKFLOW only. ***\n"
        if demo else ""
    )

    return f"""\
{demo_banner}
=== CNN PERCEPTION OUTPUT ===
Top-{len(preds)} predictions (softmax probabilities):
{_fmt_predictions(preds)}

Top-1 vs Top-2 probability gap: {gap:.2f} percentage points
Predicted condition group : {info.get('disease_group', 'n/a')}
Organ system              : {info.get('organ_system', 'n/a')}
Imaging modality          : {info.get('modality', 'n/a')}
Clinical category         : {info.get('category', 'n/a')} (severity hint: {info.get('severity_hint', 'n/a')})

=== GRAD-CAM VISUAL EVIDENCE ===
Model attention: {payload.get('gradcam_focus', 'n/a')}

=== PATIENT CONTEXT ===
{_fmt_patient(payload.get('patient_context'))}

=== CONTEXTUAL MEMORY SOURCES ===
[KB] Structured knowledge base:
  {mem.get('kb', 'n/a')}

[BioGPT] Biomedical generative context:
  {mem.get('biogpt', 'not available')}

[Med-PaLM] Clinical-QA context:
  {mem.get('medpalm', 'not available')}

=== TASK ===
Following your method and safety rules, produce the JSON interpretation now.
Return ONLY the JSON object.
"""


